//! PR-shepherd Phase 5 — remediation-plan generation + last-resort vet-imp/fix
//! session spawn. Part of plan `2026-07-04-runner-pr-shepherd.md`.
//!
//! On a CONFIRMED coord defect (Phase 3 `ShepherdIntent::Escalate`) that a
//! reevaluate nudge did not clear, or a dead-author `orphaned-red` fallback
//! (Phase 4), this module:
//!
//! 1. Renders a coord-defect remediation plan into `D:/qontinui-root/plans/`
//!    ([`render_remediation_plan`] — PURE, unit-tested from recorded evidence).
//! 2. **Dedupes** before writing (Phase 5.4 coexistence): an OPEN plan for the
//!    same defect class already in `plans/` (covers the fleet-wide
//!    `merge-train-steward`, which authors into the same dir + runs the same
//!    `/vet-imp`), OR a `pr_shepherd_remediations` marker row younger than the
//!    cooldown, is a dedup hit → skip.
//! 3. Spawns a child `TaskRun` running `/vet-imp <plan>` (or a bounded
//!    diagnose/shepherd prompt for `orphaned-red` — the PR there is GREEN but
//!    unowned while coord is down) — but ONLY when `QONTINUI_PR_SHEPHERD_SPAWN`
//!    is on. With spawn off the plan + marker are still written; no session.
//!
//! The runner daemon is the LAST-RESORT rung beneath coord's own Unlandable
//! Shepherd and the merge-train-steward — the only rung that still fires when
//! coord is the broken component. Coexistence rung (i) — "coord's shepherd has
//! a live attempt for this (PR, head)" — is checked at the call site
//! (`watchers::pr_watcher`) via
//! [`super::coord_pr_merge_client::CoordPrMergeClient::unlandable_attempt_live`]
//! before this module is invoked.

use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::database::pg::PgDb;
use crate::trigger_system::watchers::pr_watcher::PrWatcherDeps;

/// The canonical plans directory (shared with the merge-train-steward).
const PLANS_DIR: &str = "D:/qontinui-root/plans";

/// The evidence bundle a remediation plan renders from. Every field is either a
/// coord-reported value (verdict/events/graph) or a runner witness, so
/// [`render_remediation_plan`] is a pure function of this struct.
#[derive(Debug, Clone)]
pub struct RemediationPlanContext {
    /// `YYYY-MM-DD` (from `chrono::Utc::now()` at the call site — never a
    /// workflow-script `Date::now`).
    pub date: String,
    /// The `CoordDefectClass` kebab id (e.g. `stale-ingest`).
    pub defect_class: String,
    /// The suspected coord code path hint for this class.
    pub suspected_coord_path: String,
    pub repo_full_name: String,
    pub pr_number: u64,
    pub head_sha: String,
    /// How long the PR has been green-but-unmerged (the streak).
    pub green_for_secs: u64,
    /// Verdict `outer_state` (coord's `OuterState`).
    pub outer_state: Option<String>,
    /// Verdict `block_reason` (coord's `BlockReason::code`).
    pub block_reason: Option<String>,
    /// Verdict `next_action` prose.
    pub next_action: String,
    /// The newest `predicate_eval` `detail` evidence blob (verbatim).
    pub block_detail: Value,
    /// Newest `unlandable_cycle` counter.
    pub unlandable_cycles: Option<u64>,
    /// Dep-graph cycle detected for this PR's component.
    pub cycle_detected: bool,
    /// Members in that cycle.
    pub cycle_member_count: usize,
    /// The runner reached coord's verdict.
    pub coord_reachable: bool,
    /// Coord's leader lease was fresh.
    pub leader_healthy: bool,
}

/// The stable plan filename for a `(date, class, pr)` — the naming the plans-dir
/// dedup scan keys on (`coord-<class>-`).
pub fn plan_filename(date: &str, defect_class: &str, pr: u64) -> String {
    format!("{date}-coord-{defect_class}-{pr}.md")
}

/// Render a coord-defect remediation plan (Markdown). PURE — no IO, no clock.
