    #[test]
    fn open_plan_exists_matches_class_and_openness() {
        let dir = std::env::temp_dir().join(format!(
            "prshep-plans-{}",
            uuid::Uuid::new_v4().to_string().chars().take(8).collect::<String>()
        ));
        std::fs::create_dir_all(&dir).unwrap();

        // No plan yet.
        assert!(!open_plan_exists(&dir, "stale-ingest"));

        // An OPEN plan for the class → hit.
        std::fs::write(
            dir.join("2026-07-07-coord-stale-ingest-708.md"),
            "# x\n> Status: DRAFT\n",
        )
        .unwrap();
        assert!(open_plan_exists(&dir, "stale-ingest"));
        // A different class is unaffected.
        assert!(!open_plan_exists(&dir, "phantom-context-hang"));

        // A CLOSED plan for another class → not a hit.
        std::fs::write(
            dir.join("2026-07-01-coord-pass-but-no-land-500.md"),
            "# y\n> **Status: LANDED.**\n",
        )
        .unwrap();
        assert!(!open_plan_exists(&dir, "pass-but-no-land"));

        let _ = std::fs::remove_dir_all(&dir);
    }
