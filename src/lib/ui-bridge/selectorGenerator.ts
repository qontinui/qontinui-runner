/**
 * Generate Qontinui action code
 */
export function generateQontinuiCode(
  element: ExternalElement,
  action: AutomationAction = "click",
  value?: string,
): CodeSnippetResult {
  // Use the element's ref (e.g., @e1) if available, otherwise fall back to ID
  const target = element.ref || `@${element.id}`;

  let code: string;
  switch (action) {
    case "fill":
    case "type":
      code = `- action: type\n  target: "${target}"\n  value: "${value || ""}"`;
      break;
    case "hover":
      code = `- action: hover\n  target: "${target}"`;
      break;
    case "focus":
      code = `- action: focus\n  target: "${target}"`;
      break;
    case "check":
      code = `- action: check\n  target: "${target}"`;
      break;
    case "select":
      code = `- action: select\n  target: "${target}"\n  value: "${value || ""}"`;
      break;
    case "click":
    default:
      code = `- action: click\n  target: "${target}"`;
  }

  return {
    code,
    framework: "Qontinui",
    language: "yaml",
  };
}

/**
 * Generate Selenium WebDriver code snippet
 */
export function generateSeleniumCode(
  element: ExternalElement,
  action: AutomationAction = "click",
  value?: string,
): CodeSnippetResult {
  const cssResult = generateCssSelector(element);
  const selector = cssResult.selector.replace(/"/g, '\\"');

  let code: string;
  switch (action) {
    case "fill":
    case "type":
      code = `driver.find_element(By.CSS_SELECTOR, "${selector}").send_keys("${value || ""}")`;
      break;
    case "hover":
      code = `ActionChains(driver).move_to_element(driver.find_element(By.CSS_SELECTOR, "${selector}")).perform()`;
      break;
    case "focus":
      code = `driver.find_element(By.CSS_SELECTOR, "${selector}").send_keys("")`;
      break;
    case "click":
    default:
      code = `driver.find_element(By.CSS_SELECTOR, "${selector}").click()`;
  }

  return {
    code,
    framework: "Selenium",
    language: "python",
  };
}

/**
 * Get all available selectors for an element
 */
export function getAllSelectors(element: ExternalElement): SelectorResult[] {
  const results: SelectorResult[] = [];

  // Always include CSS selector
  results.push(generateCssSelector(element));

  // Always include XPath
  results.push(generateXPath(element));

  // Include test ID if available
  const testIdResult = generateTestIdSelector(element);
  if (testIdResult) {
    results.push(testIdResult);
  }

  // Include accessible selector if available
  const accessibleResult = generateAccessibleSelector(element);
  if (accessibleResult) {
    results.push(accessibleResult);
  }

  // Sort by reliability (highest first)
  results.sort((a, b) => b.reliability - a.reliability);

  return results;
}

/**
 * Get the best selector for an element
 */
export function getBestSelector(element: ExternalElement): SelectorResult {
  const all = getAllSelectors(element);
  return all[0];
}
